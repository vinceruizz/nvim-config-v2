-- Run with the full config and NVIM_THEME_STATE_FILE pointing into a temp directory.
local theme = require("config.theme")
local root = vim.fn.tempname()
vim.fn.mkdir(root, "p")
local source = vim.fn.stdpath("config") .. "/lua/themes"
local state = root .. "/preferences.json"
for _, id in ipairs({"forest-cartridge", "midnight"}) do
    vim.fn.writefile(vim.fn.readfile(source .. "/" .. id .. ".lua"), root .. "/" .. id .. ".lua")
end
local failures = {}
local function check(name, action)
    local ok, err = pcall(action)
    if ok then print("PASS: " .. name) else failures[#failures + 1] = name .. ": " .. tostring(err) end
end
local function color(name, key)
    return vim.api.nvim_get_hl(0, {name=name, link=false})[key]
end
local editor = vim.api.nvim_get_current_win()
theme.setup({palette_dir=root, state_file=state})
check("Forest default and shared highlights", function()
    assert(vim.g.colors_name == "forest-cartridge")
    assert(color("Normal", "bg") == 0x080A06)
    assert(color("String", "fg") == 0xB7CB70)
    assert(color("NvimTreeFolderName", "fg") == 0xB7CB70)
    assert(color("DapBreakpoint", "fg") == 0xDC7868)
    assert(color("CheatHeading", "fg") == 0xE8AC54)
    assert(not vim.api.nvim_get_hl(0, {name="Comment"}).italic)
end)
check("Midnight switch and persisted selection", function()
    assert(theme.set("midnight"))
    assert(vim.g.colors_name == "midnight")
    assert(color("Normal", "bg") == nil)
    assert(color("String", "fg") == 0x98C379)
    local saved = vim.json.decode(table.concat(vim.fn.readfile(state), "\n"))
    assert(saved.theme == "midnight")
    theme.setup({palette_dir=root, state_file=state})
    assert(vim.g.colors_name == "midnight")
end)
check("Transparency is remembered per theme", function()
    theme.toggle_transparency()
    assert(color("Normal", "bg") == 0x070F1C)
    theme.set("forest-cartridge")
    assert(color("Normal", "bg") == 0x080A06)
    theme.toggle_transparency()
    assert(color("Normal", "bg") == nil)
    theme.set("midnight")
    assert(color("Normal", "bg") == 0x070F1C)
    theme.set("forest-cartridge")
    assert(color("Normal", "bg") == nil)
    theme.toggle_transparency()
end)
check("Real BufWritePost hot reload", function()
    local path = root .. "/forest-cartridge.lua"
    vim.cmd("edit " .. vim.fn.fnameescape(path))
    local lines = vim.api.nvim_buf_get_lines(0,0,-1,false)
    for i, line in ipairs(lines) do lines[i] = line:gsub("#B7CB70", "#ABCDEF") end
    vim.api.nvim_buf_set_lines(0,0,-1,false,lines)
    vim.cmd("write")
    assert(color("String", "fg") == 0xABCDEF)
    assert(color("NvimTreeFolderName", "fg") == 0xABCDEF)
    assert(color("CheatTitle", "fg") == 0xABCDEF)
end)
check("Bad palette preserves live colors", function()
    local before = color("Normal", "bg")
    local notify = vim.notify
    vim.notify = function() end
    for _, contents in ipairs({ "return {colors={}}", "return { this is not Lua" }) do
        vim.fn.writefile({contents}, root .. "/forest-cartridge.lua")
        assert(not theme.reload())
    end
    vim.notify = notify
    assert(color("Normal", "bg") == before)
    assert(color("String", "fg") == 0xABCDEF)
    vim.fn.writefile(vim.fn.readfile(source .. "/forest-cartridge.lua"), root .. "/forest-cartridge.lua")
    assert(theme.reload())
end)
check("Existing float and cheat sheet follow theme", function()
    local sheet = require("config.cheatsheet")
    sheet.toggle()
    local win, buf = vim.api.nvim_get_current_win(), vim.api.nvim_get_current_buf()
    local contents = function() return table.concat(vim.api.nvim_buf_get_lines(buf,0,-1,false), "\n") end
    assert(contents():find("┌",1,true))
    theme.set("midnight")
    assert(contents():find("╭",1,true))
    assert(vim.api.nvim_win_get_config(win).border[1] == "╭")
    theme.set("forest-cartridge")
    assert(contents():find("┌",1,true))
    assert(vim.api.nvim_win_get_config(win).border[1] == "┌")
    sheet.close()
end)
check("Status bar and newly opened floats follow theme", function()
    local config = require("lualine").get_config()
    assert(config.options.theme.normal.a.bg == "#B7CB70")
    assert(config.sections.lualine_a[1].fmt("NORMAL") == "[ NORMAL ]")
    local buf = vim.api.nvim_create_buf(false,true)
    local win = vim.api.nvim_open_win(buf,false,{relative="editor",row=2,col=2,width=20,height=3,border="rounded"})
    assert(vim.wait(200,function() return vim.api.nvim_win_get_config(win).border[1] == "┌" end,10))
    vim.api.nvim_win_close(win,true)
    vim.api.nvim_buf_delete(buf,{force=true})
    theme.set("midnight")
    config = require("lualine").get_config()
    assert(config.options.theme.normal.a.bg == "#86DBF5")
    assert(config.sections.lualine_a[1].fmt("NORMAL") == "NORMAL")
    theme.set("forest-cartridge")
end)
check("Explorer focus highlight survives switches", function()
    local toggle = require("config.explorer").toggle_focus
    toggle()
    local tree = vim.api.nvim_get_current_win()
    assert(vim.bo.filetype == "NvimTree")
    theme.set("midnight")
    assert(vim.wo[tree].cursorline)
    toggle()
    theme.set("forest-cartridge")
    assert(not vim.wo[tree].cursorline and vim.wo.cursorline)
    require("nvim-tree.api").tree.close()
end)
check("Built-in colorscheme command and shortcuts", function()
    vim.cmd("colorscheme midnight")
    assert(theme.get().id == "midnight")
    vim.cmd("colorscheme forest-cartridge")
    assert(vim.fn.maparg(" ut", "n",false,true).callback)
    assert(vim.fn.maparg(" ub", "n",false,true).callback)
    vim.cmd("ThemeReload")
end)
vim.api.nvim_set_current_win(editor)
vim.fn.delete(root,"rf")
for _, failure in ipairs(failures) do print("FAIL: " .. failure) end
vim.cmd(#failures == 0 and "qa!" or "cquit")
